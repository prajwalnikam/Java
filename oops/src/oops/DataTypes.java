package oops;

public class DataTypes {
	
	byte b1;
	short s1;
	boolean b;
	int i;
	char c;
	String str;
	double d1;
	float f;
	long l;
	
	public static void main(String [] args) {
		
		DataTypes d= new DataTypes();
		System.out.println("Default value of Byte: - "+d.b1);
		System.out.println("Default value of Short: - "+d.s1);
		System.out.println("Default value of Boolean: - "+d.b);
		System.out.println("Default value of Int: - "+d.i);
		System.out.println("Default value of Char: - "+d.c);
		System.out.println("Default value of String: - "+d.str);
		System.out.println("Default value of Double: - "+d.d1);
		System.out.println("Default value of Float - "+d.f);
		System.out.println("Default value of Long: - "+d.l);
	}
	

}
